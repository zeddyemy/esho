/**
 * Generates supabase/seed.sql from the typed seed modules in src/lib/seed,
 * so the database starts with exactly the content the site was designed with.
 *
 *   pnpm seed:sql
 *
 * The output is idempotent for content tables (it clears them first) and
 * never touches admins or inquiries.
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import {
  seedAbout,
  seedContact,
  seedHome,
  seedSettings,
  seedWorkHeader,
  seedWritingHeader,
} from '../src/lib/seed/site'
import { seedProjects } from '../src/lib/seed/projects'
import { seedPosts } from '../src/lib/seed/posts'
import { seedExperiences, seedStackGroups, seedTestimonials } from '../src/lib/seed/about'

const q = (v: string | null | undefined) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`)
const j = (v: unknown) => (v == null ? 'null' : `${q(JSON.stringify(v))}::jsonb`)
const arr = (v: Array<string>) => (v.length ? `array[${v.map(q).join(', ')}]::text[]` : `'{}'::text[]`)
const bool = (v: boolean) => (v ? 'true' : 'false')

const out: Array<string> = [
  '-- Generated by scripts/generate-seed.ts. Do not edit by hand.',
  'begin;',
  'delete from public.projects;',
  'delete from public.posts;',
  'delete from public.experiences;',
  'delete from public.stack_groups;',
  'delete from public.testimonials;',
  'delete from public.page_content;',
  'delete from public.site_settings;',
  '',
]

const s = seedSettings
out.push(
  `insert into public.site_settings (id, brand_name, owner_name, role_title, tagline, logo, portrait, availability, open_to_work, email, phones, whatsapp, location, socials, resume, footer_note, show_writing, show_testimonials, show_resume, seo) values (1, ${q(s.brandName)}, ${q(s.ownerName)}, ${q(s.roleTitle)}, ${q(s.tagline)}, ${j(s.logo)}, ${j(s.portrait)}, ${q(s.availability)}, ${bool(s.openToWork)}, ${q(s.email)}, ${arr(s.phones)}, ${q(s.whatsapp)}, ${q(s.location)}, ${j(s.socials)}, ${j(s.resume)}, ${q(s.footerNote)}, ${bool(s.showWriting)}, ${bool(s.showTestimonials)}, ${bool(s.showResume)}, ${j(s.seo)});`,
  '',
)

const sections: Array<[string, string, unknown]> = [
  ['home', 'hero', seedHome.hero],
  ['home', 'intro', seedHome.intro],
  ['home', 'capabilities', seedHome.capabilities],
  ['home', 'cta', seedHome.cta],
  ['about', 'main', seedAbout],
  ['contact', 'main', seedContact],
  ['work', 'header', seedWorkHeader],
  ['writing', 'header', seedWritingHeader],
]
for (const [page, section, data] of sections) {
  out.push(`insert into public.page_content (page, section, data) values (${q(page)}, ${q(section)}, ${j(data)});`)
}
out.push('')

for (const p of seedProjects) {
  out.push(
    `insert into public.projects (slug, title, summary, role, client, year, tags, stack, links, metrics, cover, gallery, body, featured, published, sort_order) values (${q(p.slug)}, ${q(p.title)}, ${q(p.summary)}, ${q(p.role)}, ${q(p.client)}, ${p.year}, ${arr(p.tags)}, ${arr(p.stack)}, ${j(p.links)}, ${j(p.metrics)}, ${j(p.cover)}, ${j(p.gallery)}, ${q(p.body)}, ${bool(p.featured)}, ${bool(p.published)}, ${p.sortOrder});`,
  )
}
out.push('')

for (const p of seedPosts) {
  out.push(
    `insert into public.posts (slug, title, excerpt, cover, body, tags, reading_minutes, published, published_at) values (${q(p.slug)}, ${q(p.title)}, ${q(p.excerpt)}, ${j(p.cover)}, ${q(p.body)}, ${arr(p.tags)}, ${p.readingMinutes}, ${bool(p.published)}, ${q(p.publishedAt)});`,
  )
}
out.push('')

for (const e of seedExperiences) {
  out.push(
    `insert into public.experiences (kind, organisation, title, location, url, start_date, end_date, summary, highlights, stack, visible, sort_order) values (${q(e.kind)}, ${q(e.organisation)}, ${q(e.title)}, ${q(e.location)}, ${q(e.url)}, ${q(e.startDate)}, ${q(e.endDate)}, ${q(e.summary)}, ${arr(e.highlights)}, ${arr(e.stack)}, ${bool(e.visible)}, ${e.sortOrder});`,
  )
}
for (const g of seedStackGroups) {
  out.push(
    `insert into public.stack_groups (title, description, items, visible, sort_order) values (${q(g.title)}, ${q(g.description)}, ${arr(g.items)}, ${bool(g.visible)}, ${g.sortOrder});`,
  )
}
for (const t of seedTestimonials) {
  out.push(
    `insert into public.testimonials (quote, name, role, company, avatar, visible, sort_order) values (${q(t.quote)}, ${q(t.name)}, ${q(t.role)}, ${q(t.company)}, ${j(t.avatar)}, ${bool(t.visible)}, ${t.sortOrder});`,
  )
}

out.push('', 'commit;', '')

const target = resolve(import.meta.dirname, '../supabase/seed.sql')
writeFileSync(target, out.join('\n'))
console.log(`Wrote ${target}`)
